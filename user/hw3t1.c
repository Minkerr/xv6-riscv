/**
 * @file hw3t1.c
 * @brief Тестовая программа для демонстрации работы мьютексов
 * 
 * Эта программа демонстрирует разницу между выводом на консоль с использованием
 * мьютексов и без них. Сначала программа создает два процесса, которые выводят
 * информацию без синхронизации, что приводит к перемешиванию вывода. Затем
 * программа создает еще два процесса, которые используют мьютекс для синхронизации
 * вывода, что предотвращает перемешивание.
 */

#include "kernel/types.h"  // Базовые типы данных
#include "kernel/stat.h"   // Структуры статистики
#include "user/user.h"     // Пользовательские функции

/**
 * @brief Основная функция программы
 * 
 * @param argc Количество аргументов командной строки
 * @param argv Массив аргументов командной строки
 * @return Код завершения программы
 */
int main(int argc, char *argv[]) {
    // Создаем мьютекс для синхронизации вывода
    int m = mutex(); 

    // ЧАСТЬ 1: Вывод без синхронизации
    
    // Создаем дочерний процесс
    if (fork() == 0) {
        // Код дочернего процесса
        // Выводим каждый символ каждого аргумента командной строки
        for (int i = 1; i < argc; i++) {
            for (char *c = argv[i]; *c; c++) {
                printf("%d: arg %d, char '%c'\n", getpid(), i, *c);
            }
        }
        exit(0);  // Завершаем дочерний процесс
    }
    
    // Код родительского процесса
    // Выводим каждый символ каждого аргумента командной строки
    for (int i = 1; i < argc; i++) {
        for (char *c = argv[i]; *c; c++) {
            printf("%d: arg %d, char '%c'\n", getpid(), i, *c);
        }
    }
    wait(0);  // Ожидаем завершения дочернего процесса
    
    // ЧАСТЬ 2: Вывод с синхронизацией через мьютекс
    
    // Создаем еще один дочерний процесс
    if (fork() == 0) {
        // Код дочернего процесса
        // Выводим каждый символ каждого аргумента командной строки,
        // но теперь с блокировкой мьютекса перед выводом
        for (int i = 1; i < argc; i++) {
            for (char *c = argv[i]; *c; c++) {
                mutex_lock(m);  // Захватываем мьютекс перед выводом
                printf("%d: arg %d, char '%c'\n", getpid(), i, *c);
                mutex_unlock(m);  // Освобождаем мьютекс после вывода
            }
        }
        exit(0);  // Завершаем дочерний процесс
    }
    
    // Код родительского процесса
    // Выводим каждый символ каждого аргумента командной строки,
    // но теперь с блокировкой мьютекса перед выводом
    for (int i = 1; i < argc; i++) {
        for (char *c = argv[i]; *c; c++) {
            mutex_lock(m);  // Захватываем мьютекс перед выводом
            printf("%d: arg %d, char '%c'\n", getpid(), i, *c);
            mutex_unlock(m);  // Освобождаем мьютекс после вывода
        }
    }
    wait(0);  // Ожидаем завершения дочернего процесса
    close(m);  // Закрываем мьютекс
    exit(0);  // Завершаем родительский процесс
}