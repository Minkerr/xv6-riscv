#include "kernel/types.h"  // Включение необходимых заголовочных файлов для типов данных
#include "kernel/stat.h"   // Включение заголовочного файла для структуры stat
#include "user/user.h"     // Включение заголовочного файла для пользовательских функций

#define MAX_LEN 512        // Определение максимальной длины буфера для передачи данных
char buf[MAX_LEN];         // Буфер для хранения данных, передаваемых через канал

/**
 * Основная функция программы
 * Создает дочерний процесс и передает ему через анонимный канал все аргументы командной строки,
 * после чего дочерний процесс выполняет команду wc для подсчета строк, слов и байтов
 * @param argc - количество аргументов командной строки
 * @param argv - массив аргументов командной строки
 * @return код завершения программы
 */
int 
main(int argc, char *argv[]) 
{
    int pipefd[2];         // Массив для хранения файловых дескрипторов канала
    int status;            // Переменная для хранения статуса завершения дочернего процесса
    int i, len;            // Переменные для цикла и длины аргумента

    // Создаем анонимный канал с помощью системного вызова pipe()
    // pipe() заполняет массив pipefd двумя файловыми дескрипторами:
    // pipefd[0] - для чтения из канала
    // pipefd[1] - для записи в канал
    if (pipe(pipefd) < 0) {
        printf("pipe has failed\n");  // Выводим сообщение об ошибке
        exit(1);                      // Завершаем программу с кодом ошибки 1
    }

    // Создаем дочерний процесс с помощью системного вызова fork()
    int pid = fork();

    // Проверяем, успешно ли создан дочерний процесс
    if (pid < 0) {
        printf("fork has failed\n");  // Выводим сообщение об ошибке
        exit(1);                      // Завершаем программу с кодом ошибки 1
    }
    
    // Код, выполняемый в дочернем процессе
    if (pid == 0) {  
        // Закрываем конец канала для записи, так как дочерний процесс будет только читать
        if (close(pipefd[1]) < 0) {
            printf("failed to close write end\n");
            exit(1);
        }
        
        // Закрываем стандартный ввод (файловый дескриптор 0)
        if (close(0) < 0) {
            printf("failed to close stdin\n");
            exit(1);
        }
        
        // Дублируем файловый дескриптор для чтения из канала на место стандартного ввода
        // dup() выбирает наименьший свободный файловый дескриптор (в данном случае 0)
        // и дублирует на него указанный файловый дескриптор
        if (dup(pipefd[0]) != 0) {
            printf("dup has failed\n");
            exit(1);
        }
        
        // Закрываем оригинальный файловый дескриптор для чтения из канала,
        // так как теперь мы можем читать через стандартный ввод
        if (close(pipefd[0]) < 0) {
            printf("failed to close pipefd[0]\n");
            exit(1);
        }

        // Подготавливаем аргументы для запуска команды wc
        char *args[] = { "wc", 0 };
        // Заменяем текущий процесс на процесс wc с помощью системного вызова exec()
        // exec() загружает программу wc и передает ей указанные аргументы
        exec("/wc", args);

        // Этот код выполнится только если exec() завершился с ошибкой
        printf("exec wc has failed\n");
        exit(1);
    } 
    else {  // Код, выполняемый в родительском процессе
        // Закрываем конец канала для чтения, так как родительский процесс будет только писать
        if (close(pipefd[0]) < 0) {
            printf("failed to close read end\n");
            exit(1);
        }
        
        // Перебираем все аргументы командной строки, начиная с первого (индекс 0 - имя программы)
        for (i = 1; i < argc; i++) {
            len = strlen(argv[i]);  // Получаем длину текущего аргумента
            // Проверяем, не превышает ли длина аргумента максимально допустимую
            if (len >= MAX_LEN - 1) {  
                printf("argument is too long\n");
                // Закрываем канал в случае ошибки
                if (close(pipefd[1]) < 0) {
                    printf("failed to close pipe after error\n");
                }
                wait(&status);  // Ожидаем завершения дочернего процесса
                exit(1);        // Завершаем программу с кодом ошибки
            }
            
            // Копируем аргумент в буфер
            memcpy(buf, argv[i], len);
            buf[len] = '\n';  // Добавляем символ перевода строки после аргумента
            
            // Записываем аргумент в канал
            int remaining = len + 1;  // Количество байт, которые нужно записать
            char *p = buf;            // Указатель на текущую позицию в буфере
            // Цикл записи данных в канал
            // Системный вызов write() может записать меньше байт, чем запрошено,
            // поэтому мы продолжаем запись, пока не запишем все данные
            while (remaining > 0) {
                int written = write(pipefd[1], p, remaining);
                // Проверяем, успешно ли выполнена запись
                if (written < 0) {
                    printf("write error\n");
                    // Закрываем канал в случае ошибки
                    if (close(pipefd[1]) < 0) {
                        printf("failed to close pipe after error\n");
                    }
                    wait(&status);  // Ожидаем завершения дочернего процесса
                    exit(1);        // Завершаем программу с кодом ошибки
                }
                remaining -= written;  // Уменьшаем количество оставшихся байт
                p += written;          // Сдвигаем указатель в буфере
            }
        }
        
        // Закрываем конец канала для записи, чтобы дочерний процесс получил EOF
        if (close(pipefd[1]) < 0) {
            printf("failed to close write end in parent\n");
            wait(&status);  // Ожидаем завершения дочернего процесса
            exit(1);        // Завершаем программу с кодом ошибки
        }
        
        // Ожидаем завершения дочернего процесса
        wait(&status);
        exit(0);  // Завершаем родительский процесс с кодом успешного выполнения
    }
}