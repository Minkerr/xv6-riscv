/**
 * @file test.c
 * @brief Тестовая программа для системных вызовов pageinfo и clearflags
 * 
 * Эта программа тестирует работу системных вызовов pageinfo и clearflags,
 * демонстрируя их работу на различных типах переменных (глобальных, стековых,
 * и динамически выделенных в куче) и показывая изменение флагов доступа (A)
 * и изменения (D) при различных операциях.
 */

#include "kernel/types.h"  // Базовые типы данных
#include "kernel/stat.h"   // Структуры статистики
#include "user/user.h"     // Пользовательские функции

#define PGSIZE 4096        // Размер страницы в байтах
#define ARRAY_PAGES 3      // Количество страниц для массива в куче

/**
 * @brief Глобальная переменная для тестирования
 * 
 * Используется для демонстрации работы с глобальными переменными,
 * которые размещаются в секции данных программы.
 */
int global_var = 64;

/**
 * @brief Выводит разделитель для улучшения читаемости вывода
 */
void print_separator(void) {
  printf("----------------------------------------\n");
}

/**
 * @brief Основная функция программы
 * 
 * Тестирует системные вызовы pageinfo и clearflags на различных типах переменных
 * и демонстрирует изменение флагов при различных операциях.
 * 
 * @param argc Количество аргументов командной строки
 * @param argv Массив аргументов командной строки
 * @return Код завершения программы
 */
int
main(int argc, char *argv[])
{
  /**
   * @brief Локальная переменная на стеке
   * 
   * Используется для демонстрации работы со стековыми переменными.
   */
  int stack_var = 100;
  
  /**
   * @brief Указатель на массив в куче
   * 
   * Используется для демонстрации работы с динамически выделенной памятью.
   */
  int *heap_array;
  int i;

  // Выводим разделитель для улучшения читаемости
  print_separator();

  // Выводим информацию о всех страницах процесса
  // Первый аргумент (0) - указатель на буфер (0 означает все страницы)
  // Второй аргумент (0) - длина буфера (0 означает все страницы)
  // Третий аргумент (0) - маска флагов (0 означает вывод всех страниц)
  pageinfo(0, 0, 0);
  print_separator();

  printf("\n\n");
  // Выделяем память для массива в куче
  // Размер массива - ARRAY_PAGES * PGSIZE байт (3 страницы)
  heap_array = (int*)malloc(ARRAY_PAGES * PGSIZE);
  if (heap_array == 0) {
    printf("malloc failed\n");
    exit(1);
  }

  // Инициализируем массив, записывая в каждый элемент его индекс
  // Это установит флаг D (dirty) для страниц массива
  for (i = 0; i < (ARRAY_PAGES * PGSIZE / sizeof(int)); i++) {
    heap_array[i] = i;
  }

  printf("\n\n");
  // Выводим информацию о всех страницах процесса после выделения памяти
  // Здесь мы увидим новые страницы, выделенные для массива
  pageinfo(0, 0, 0);
  print_separator();

  printf("\n\n");
  // Очищаем флаги A (accessed) и D (dirty) у всех страниц процесса
  // Первый аргумент (0) - указатель на буфер (0 означает все страницы)
  // Второй аргумент (0) - длина буфера (0 означает все страницы)
  // Третий аргумент (3) - маска флагов (3 означает очистку флагов A и D)
  clearflags(0, 0, 3);
  
  printf("\n\n");
  // Выводим информацию о всех страницах процесса после очистки флагов
  // Здесь мы увидим, что флаги A и D сброшены у всех страниц
  pageinfo(0, 0, 0);
  print_separator();

  printf("\n\n");
  // Выводим информацию о странице, содержащей глобальную переменную
  // Первый аргумент (&global_var) - указатель на буфер (адрес глобальной переменной)
  // Второй аргумент (sizeof(global_var)) - длина буфера (размер глобальной переменной)
  // Третий аргумент (2) - маска флагов (2 означает вывод страниц с установленным флагом A)
  // Обращение к глобальной переменной установит флаг A для страницы, содержащей эту переменную
  pageinfo(&global_var, sizeof(global_var), 2);
  print_separator();

  printf("\n\n");
  // Выводим информацию о странице, содержащей стековую переменную
  // Первый аргумент (&stack_var) - указатель на буфер (адрес стековой переменной)
  // Второй аргумент (sizeof(stack_var)) - длина буфера (размер стековой переменной)
  // Третий аргумент (2) - маска флагов (2 означает вывод страниц с установленным флагом A)
  // Обращение к стековой переменной установит флаг A для страницы, содержащей эту переменную
  pageinfo(&stack_var, sizeof(stack_var), 2);
  print_separator();

  printf("\n\n");
  // Выводим информацию о страницах, содержащих массив в куче
  // Первый аргумент (heap_array) - указатель на буфер (адрес массива)
  // Второй аргумент (ARRAY_PAGES * PGSIZE) - длина буфера (размер массива)
  // Третий аргумент (2) - маска флагов (2 означает вывод страниц с установленным флагом A)
  // Обращение к массиву установит флаг A для страниц, содержащих этот массив
  pageinfo(heap_array, ARRAY_PAGES * PGSIZE, 2);
  print_separator();

  printf("\n\n");
  // Очищаем флаги A и D у всех страниц процесса
  clearflags(0, 0, 3);
  
  // Изменяем значение глобальной переменной
  // Это установит флаги A и D для страницы, содержащей эту переменную
  global_var = 63;
  
  printf("\n\n");
  // Выводим информацию о странице, содержащей глобальную переменную
  // Третий аргумент (3) - маска флагов (3 означает вывод страниц с установленными флагами A или D)
  // Здесь мы увидим, что флаги A и D установлены для страницы, содержащей глобальную переменную
  pageinfo(&global_var, sizeof(global_var), 3);
  print_separator();

  printf("\n\n");
  // Изменяем значение стековой переменной
  // Это установит флаги A и D для страницы, содержащей эту переменную
  stack_var = 101;
  
  printf("\n\n");
  // Выводим информацию о странице, содержащей стековую переменную
  // Третий аргумент (3) - маска флагов (3 означает вывод страниц с установленными флагами A или D)
  // Здесь мы увидим, что флаги A и D установлены для страницы, содержащей стековую переменную
  pageinfo(&stack_var, sizeof(stack_var), 3); 
  print_separator();

  printf("\n\n");
  // Изменяем значения элементов массива
  // Это установит флаги A и D для страниц, содержащих этот массив
  for (i = 0; i < (ARRAY_PAGES * PGSIZE / sizeof(int)); i++) {
    heap_array[i] = i * 2;
  }
  
  printf("\n\n");
  // Выводим информацию о страницах, содержащих массив в куче
  // Третий аргумент (3) - маска флагов (3 означает вывод страниц с установленными флагами A или D)
  // Здесь мы увидим, что флаги A и D установлены для страниц, содержащих массив
  pageinfo(heap_array, ARRAY_PAGES * PGSIZE, 3);
  print_separator();

  printf("\n\n");
  // Освобождаем память, выделенную для массива
  free(heap_array);
  
  printf("\n\n");
  // Выводим информацию о всех страницах процесса после освобождения памяти
  // Здесь мы увидим, что страницы, выделенные для массива, больше не принадлежат процессу
  pageinfo(0, 0, 0);
  print_separator();

  printf("\n\n");
  // Выводим разделители для улучшения читаемости
  print_separator();
  print_separator();
  print_separator();
  exit(0);  // Завершаем программу
}