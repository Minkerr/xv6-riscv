/**
 * @file hw2task3.c
 * @brief Расширенная тестовая программа для системного вызова ps_listinfo
 * 
 * Эта программа тестирует различные сценарии использования системного вызова ps_listinfo,
 * включая передачу NULL, недопустимого адреса и нормальное использование.
 */

#include "kernel/types.h"    // Базовые типы данных
#include "kernel/stat.h"     // Структуры статистики
#include "kernel/procinfo.h" // Структура procinfo
#include "user.h"            // Пользовательские функции

/**
 * @brief Тестирует вызов ps_listinfo с NULL в качестве первого аргумента
 * 
 * Этот тест проверяет функциональность получения общего количества процессов
 * без получения информации о них.
 */
void test_null() {
    // Вызываем ps_listinfo с NULL в качестве первого аргумента
    // Это должно вернуть общее количество процессов
    int cnt = ps_listinfo(0, 0);
    printf("Total processes: %d\n", cnt);
}

/**
 * @brief Тестирует вызов ps_listinfo с недопустимым адресом
 * 
 * Этот тест проверяет обработку ошибок при передаче недопустимого адреса
 * в качестве буфера для хранения информации о процессах.
 */
void test_invalid() {
    // Вызываем ps_listinfo с недопустимым адресом (0xDEADBEEF)
    // Это должно вернуть отрицательное значение (ошибку)
    int ret = ps_listinfo((struct procinfo*)0xDEADBEEF, 10);
    if(ret < 0) 
        printf("You can't write to invalid adress\n");
}

/**
 * @brief Тестирует нормальное использование ps_listinfo
 * 
 * Этот тест проверяет корректное получение информации о процессах
 * при нормальных условиях.
 */
void test_normal() {
    // Сначала получаем общее количество процессов
    int cnt = ps_listinfo(0, 0);
    
    // Выделяем память для буфера нужного размера
    struct procinfo *buf = malloc(cnt * sizeof(struct procinfo));
    
    // Получаем информацию о процессах
    int ret = ps_listinfo(buf, cnt);
    
    // Проверяем, что получили информацию о всех процессах
    if(ret == cnt) {
        printf("test\n");   
    }
    
    // Освобождаем выделенную память
    free(buf);
}

/**
 * @brief Основная функция программы
 * 
 * Запускает все тесты последовательно.
 * 
 * @return Код завершения программы
 */
int main() {
    test_null();     // Тест с NULL
    test_invalid();  // Тест с недопустимым адресом
    test_normal();   // Тест нормального использования
    exit(0);         // Завершаем программу с кодом успешного выполнения
}