/**
 * @file hexdump.c
 * @brief Утилита для вывода содержимого файла в шестнадцатеричном формате
 *
 * Эта программа читает указанное количество байт из файла и выводит их
 * в шестнадцатеричном формате. Используется для тестирования псевдоустройств
 * и просмотра двоичных данных в удобочитаемом виде.
 */

#include "kernel/types.h"  // Базовые типы данных
#include "kernel/stat.h"   // Структуры статистики
#include "user/user.h"     // Пользовательские функции
#include "kernel/fcntl.h"  // Константы для открытия файлов

/**
 * @brief Выводит содержимое файла в шестнадцатеричном формате
 *
 * Читает данные из файлового дескриптора блоками по 16 байт (или меньше)
 * и выводит их в шестнадцатеричном формате с указанием смещения.
 *
 * @param fd Файловый дескриптор для чтения
 * @param n Количество байт для чтения
 */
void
hexdump(int fd, int n)
{
  int i, r;
  char buf[16];  // Буфер для чтения данных блоками по 16 байт
  
  while(n > 0) {
    // Читаем блок данных (не более 16 байт)
    r = read(fd, buf, n < 16 ? n : 16);
    if(r <= 0) {
      // Если чтение вернуло 0 (конец файла) или ошибку, выходим из цикла
      break;
    }
    
    // Выводим прочитанные байты в шестнадцатеричном формате
    for(i = 0; i < r; i++) {
      if(i % 16 == 0) {
        // В начале каждой строки выводим смещение
        printf("%d: ", i);
      }
      // Выводим байт в шестнадцатеричном формате
      // Используем маску 0xff для обеспечения корректного отображения
      // отрицательных значений char как беззнаковых байтов
      printf("0x%x ", buf[i] & 0xff);
      if((i + 1) % 16 == 0) {
        // В конце каждой полной строки (16 байт) выводим перевод строки
        printf("\n");
      }
    }
    
    // Если последняя строка неполная, добавляем перевод строки
    if(r % 16 != 0) {
      printf("\n");
    }
    
    // Уменьшаем оставшееся количество байт для чтения
    n -= r;
  }
}

/**
 * @brief Основная функция программы
 *
 * Обрабатывает аргументы командной строки, открывает указанный файл
 * и вызывает функцию hexdump для вывода его содержимого.
 *
 * @param argc Количество аргументов командной строки
 * @param argv Массив аргументов командной строки
 * @return Код завершения программы
 */
int
main(int argc, char *argv[])
{
  int fd;
  int n;
  
  // Проверяем количество аргументов
  if(argc != 3) {
    fprintf(2, "error\n");
    exit(1);
  }
  
  // Преобразуем второй аргумент (количество байт) в число
  n = atoi(argv[2]);
  if(n <= 0) {
    fprintf(2, "invalid bytes: %s\n", argv[2]);
    exit(1);
  }
  
  // Открываем файл для чтения
  if((fd = open(argv[1], O_RDONLY)) < 0) {
    fprintf(2, "cannot open %s\n", argv[1]);
    exit(1);
  }
  
  // Выводим содержимое файла в шестнадцатеричном формате
  hexdump(fd, n);
  
  // Закрываем файл
  close(fd);
  exit(0);
}