#include "kernel/types.h"  // Включение необходимых заголовочных файлов для типов данных
#include "kernel/stat.h"   // Включение заголовочного файла для структуры stat
#include "user/user.h"     // Включение заголовочного файла для пользовательских функций

/**
 * Основная функция программы
 * Реализует вариант (a) задания 1: родительский процесс ожидает завершения дочернего процесса
 * @param argc - количество аргументов командной строки
 * @param argv - массив аргументов командной строки
 * @return код завершения программы
 */
int
main(int argc, char *argv[])
{
  // Создаем дочерний процесс с помощью системного вызова fork()
  // fork() возвращает:
  // - отрицательное значение в случае ошибки
  // - 0 в дочернем процессе
  // - положительное значение (PID дочернего процесса) в родительском процессе
  int pid = fork();

  // Проверяем, успешно ли создан дочерний процесс
  if (pid < 0) {
    printf("fork has failed\n");  // Выводим сообщение об ошибке
    exit(1);                      // Завершаем программу с кодом ошибки 1
  }

  // Код, выполняемый в дочернем процессе
  if (pid == 0) {
    // Выводим сообщение о том, что дочерний процесс будет спать
    printf("Child is sleeping for 10 seconds\n");
    sleep(100);  // Приостанавливаем процесс на 100 тиков (примерно 10 секунд в xv6)
                 // Примечание: в xv6 sleep принимает количество тиков, а не миллисекунд
    exit(1);     // Завершаем дочерний процесс с кодом возврата 1
    
  } else {  // Код, выполняемый в родительском процессе
    // Выводим идентификаторы родительского и дочернего процессов
    printf("Parent pid: %d\n", getpid());  // getpid() возвращает PID текущего процесса
    printf("Child pid: %d\n", pid);        // pid содержит PID дочернего процесса
    
    int status;  // Переменная для хранения статуса завершения дочернего процесса
    // Ожидаем завершения дочернего процесса с помощью системного вызова wait()
    // wait() блокирует выполнение родительского процесса до завершения любого дочернего процесса
    // и возвращает PID завершившегося дочернего процесса
    int w_pid = wait(&status);
    
    // Проверяем, что завершился именно наш дочерний процесс
    if (w_pid != pid) {
      printf("wait error: expected %d, got %d\n", pid, w_pid);
      exit(1);  // Завершаем программу с кодом ошибки, если что-то пошло не так
    }
    
    // Выводим сообщение о завершении дочернего процесса
    printf("Child %d has exited\n", pid);
    exit(0);  // Завершаем родительский процесс с кодом успешного выполнения
  }
}