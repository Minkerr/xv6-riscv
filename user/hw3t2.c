/**
 * @file hw3t2.c
 * @brief Тестовая программа для проверки граничных случаев работы мьютексов
 * 
 * Эта программа тестирует различные граничные случаи работы мьютексов:
 * 1. Попытка чтения и записи в мьютекс
 * 2. Закрытие мьютекса, когда он захвачен текущим процессом
 * 3. Попытка освобождения мьютекса другим процессом
 */

#include "kernel/types.h"  // Базовые типы данных
#include "kernel/stat.h"   // Структуры статистики
#include "user/user.h"     // Пользовательские функции

/**
 * @brief Тестирует попытки чтения и записи в мьютекс
 * 
 * Эта функция создает мьютекс и пытается выполнить операции чтения и записи,
 * которые должны завершиться с ошибкой, так как мьютексы не поддерживают
 * эти операции.
 */
void read_write_test() {
    // Создаем мьютекс
    int m = mutex();
    char buf[10];  // Буфер для чтения
    
    // Пытаемся прочитать из мьютекса (должно завершиться с ошибкой)
    if (read(m, buf, 1) > 0) 
        printf("read succeeded\n");  // Этот код не должен выполниться
    
    // Пытаемся записать в мьютекс (должно завершиться с ошибкой)
    if (write(m, "x", 1) > 0) 
        printf("write succeeded\n");  // Этот код не должен выполниться
    
    // Закрываем мьютекс
    close(m);
}

/**
 * @brief Тестирует закрытие мьютекса, когда он захвачен текущим процессом,
 * и попытку освобождения мьютекса другим процессом
 * 
 * Эта функция создает мьютекс, захватывает его, затем создает дочерний процесс,
 * который пытается освободить мьютекс (что должно завершиться с ошибкой).
 * Родительский процесс закрывает мьютекс, что должно автоматически освободить его.
 */
void close_while_locked() {
    // Создаем мьютекс
    int m = mutex();
    // Захватываем мьютекс
    mutex_lock(m);
    
    // Создаем дочерний процесс
    if (fork() == 0) {
        // Код дочернего процесса
        sleep(10);  // Ждем, чтобы родительский процесс успел закрыть мьютекс
        
        // Пытаемся освободить мьютекс, захваченный родительским процессом
        // (должно завершиться с ошибкой)
        if (mutex_unlock(m) < 0)
            printf("unlock failed in child\n");
            
        exit(0);  // Завершаем дочерний процесс
    }
    
    // Код родительского процесса
    // Закрываем мьютекс, когда он захвачен (должен быть автоматически освобожден)
    close(m); 
    wait(0);  // Ожидаем завершения дочернего процесса
}

/**
 * @brief Основная функция программы
 * 
 * Запускает все тесты последовательно.
 * 
 * @return Код завершения программы
 */
int main() {
    // Тест чтения и записи в мьютекс
    printf("read write test:\n");
    read_write_test();
    
    // Тест закрытия захваченного мьютекса
    printf("\nclose locked test:\n");
    close_while_locked();
    
    exit(0);  // Завершаем программу
}