/**
 * @file rtc.c
 * @brief Реализация драйвера часов реального времени (RTC) для xv6
 *
 * Этот файл содержит реализацию драйвера для доступа к виртуальным часам
 * реального времени Goldfish RTC в QEMU. Драйвер позволяет считывать
 * текущее время в виде 64-битного значения, представляющего количество
 * наносекунд с 1 января 1970 года.
 */

#include "types.h"      // Базовые типы данных
#include "memlayout.h"  // Определения адресов памяти, включая RTC_LOW и RTC_HIGH
#include "riscv.h"      // Специфичные для RISC-V определения
#include "spinlock.h"   // Спин-блокировки
#include "defs.h"       // Объявления функций ядра

/**
 * @brief Считывает младшее 32-битное слово времени из регистра RTC
 *
 * Функция обращается к регистру RTC_LOW по физическому адресу 0x101000,
 * который содержит младшие 32 бита значения времени. Ключевое слово volatile
 * используется для предотвращения оптимизации доступа к памяти компилятором.
 *
 * @return Младшие 32 бита значения времени
 */
static inline uint32 rtc_read_low() {
  return *(volatile uint32*)RTC_LOW;
}

/**
 * @brief Считывает старшее 32-битное слово времени из регистра RTC
 *
 * Функция обращается к регистру RTC_HIGH по физическому адресу 0x101004,
 * который содержит старшие 32 бита значения времени. Ключевое слово volatile
 * используется для предотвращения оптимизации доступа к памяти компилятором.
 *
 * @return Старшие 32 бита значения времени
 */
static inline uint32 rtc_read_high() {
  return *(volatile uint32*)RTC_HIGH;
}

/**
 * @brief Спин-блокировка для синхронизации доступа к RTC
 *
 * Используется для предотвращения одновременного доступа к регистрам RTC
 * из разных процессов или прерываний.
 */
static struct spinlock rtclock;

/**
 * @brief Инициализирует драйвер RTC
 *
 * Инициализирует спин-блокировку для синхронизации доступа к RTC.
 * Вызывается при запуске системы.
 */
void rtcinit(void) {
  initlock(&rtclock, "rtc");
}

/**
 * @brief Считывает текущее время из RTC
 *
 * Функция считывает 64-битное значение времени из регистров RTC.
 * Сначала считывается старшее слово, затем младшее, и затем снова проверяется
 * старшее слово. Если старшее слово изменилось, процесс повторяется.
 * Это необходимо для обеспечения атомарности чтения 64-битного значения
 * через два 32-битных регистра.
 *
 * @return 64-битное значение времени в наносекундах с 1 января 1970 года
 */
uint64 rtc_read_time() {
  uint32 low, high;

  acquire(&rtclock);  // Захватываем блокировку

  do {
    high = rtc_read_high();  // Считываем старшее слово
    low = rtc_read_low();    // Считываем младшее слово
  } while (high != rtc_read_high());  // Проверяем, не изменилось ли старшее слово
  // Если старшее слово изменилось, значит, произошло переполнение младшего слова
  // во время чтения, и нужно повторить процесс

  release(&rtclock);  // Освобождаем блокировку

  // Объединяем старшее и младшее слова в 64-битное значение
  return ((uint64)high << 32) | low;
}