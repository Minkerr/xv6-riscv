/**
 * @file procinfo.h
 * @brief Определение структуры для хранения информации о процессе
 * 
 * Этот заголовочный файл содержит определение структуры procinfo,
 * которая используется для передачи информации о процессах между
 * пространством ядра и пользовательским пространством.
 */

#ifndef _PROCINFO_H
#define _PROCINFO_H

/**
 * @struct procinfo
 * @brief Структура для хранения информации о процессе
 * 
 * Эта структура содержит основную информацию о процессе:
 * идентификатор процесса, имя, состояние и идентификатор родительского процесса.
 * Структура доступна как из пространства ядра, так и из пользовательского пространства.
 */
struct procinfo {
    int pid;       // Идентификатор процесса
    char name[16]; // Имя процесса (ограничено 16 символами, включая нулевой символ)
    int state;     // Состояние процесса (UNUSED, USED, SLEEPING, RUNNABLE, RUNNING, ZOMBIE)
    int ppid;      // Идентификатор родительского процесса
};

#endif