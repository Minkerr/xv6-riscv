/**
 * @file mutex.c
 * @brief Реализация функциональности мьютексов в ядре xv6
 * 
 * Этот файл содержит реализацию функций для создания, использования и
 * освобождения мьютексов. Мьютексы реализованы как файловые дескрипторы,
 * что позволяет использовать существующую инфраструктуру файловой системы
 * для управления ими.
 */

#include "types.h"      // Базовые типы данных
#include "param.h"      // Параметры системы
#include "spinlock.h"   // Спин-блокировки
#include "sleeplock.h"  // Слип-блокировки
#include "fs.h"         // Файловая система
#include "file.h"       // Файловые дескрипторы
#include "memlayout.h"  // Макеты памяти
#include "riscv.h"      // Специфичные для RISC-V определения
#include "defs.h"       // Объявления функций ядра

/**
 * @brief Счетчик созданных мьютексов
 * 
 * Используется для присвоения уникальных идентификаторов мьютексам.
 */
static int mutex_counter = 0;

/**
 * @brief Спин-блокировка для защиты счетчика мьютексов
 * 
 * Предотвращает гонки данных при обновлении счетчика мьютексов.
 */
static struct spinlock mutex_counter_lock; 

/**
 * @brief Инициализирует подсистему мьютексов
 * 
 * Инициализирует спин-блокировку для защиты счетчика мьютексов.
 * Вызывается при первом создании мьютекса.
 */
void init_mutex_subsystem() {
  initlock(&mutex_counter_lock, "mutex_counter");
}

/**
 * @brief Создает новый мьютекс
 * 
 * Эта функция выделяет файловую структуру и слип-блокировку для нового мьютекса,
 * инициализирует их и возвращает указатель на файловую структуру.
 * 
 * @return Указатель на файловую структуру мьютекса или 0 в случае ошибки
 */
struct file* mutexalloc() {
  // Инициализируем подсистему мьютексов, если это первый вызов
  init_mutex_subsystem();
  
  // Выделяем файловую структуру для мьютекса
  struct file *f = filealloc();
  if(!f) return 0;  // Если не удалось выделить файловую структуру, возвращаем ошибку

  // Выделяем память для слип-блокировки
  struct sleeplock *sl = (struct sleeplock*)kalloc();
  
  // Присваиваем уникальный идентификатор мьютексу
  acquire(&mutex_counter_lock);  // Захватываем спин-блокировку для защиты счетчика
  sl->mid = ++mutex_counter;     // Увеличиваем счетчик и присваиваем идентификатор
  release(&mutex_counter_lock);  // Освобождаем спин-блокировку
  
  // Выводим отладочное сообщение о создании мьютекса
  printf("mutexalloc: created mutex#%d\n", sl->mid); 

  // Проверяем, удалось ли выделить память для слип-блокировки
  if(!sl) {
    fileclose(f);  // Если не удалось, закрываем файловую структуру
    return 0;      // и возвращаем ошибку
  }

  // Инициализируем слип-блокировку
  initsleeplock(sl, "mutex");
  
  // Настраиваем файловую структуру
  f->type = FD_MUTEX;       // Тип файла - мьютекс
  f->mutex = sl;            // Указатель на слип-блокировку
  f->readable = f->writable = 0;  // Мьютекс нельзя читать или писать
  
  return f;  // Возвращаем указатель на файловую структуру
}

/**
 * @brief Закрывает мьютекс
 * 
 * Эта функция освобождает ресурсы, связанные с мьютексом,
 * когда он больше не нужен (когда счетчик ссылок на него становится равным 0).
 * 
 * @param f Указатель на файловую структуру мьютекса
 */
void mutexclose(struct file *f) {
  // Выводим отладочное сообщение о закрытии мьютекса
  printf("mutexclose: destroying mutex#%d\n", f->mutex->mid);
  
  // Освобождаем память, выделенную для слип-блокировки
  kfree(f->mutex);
  
  // Обнуляем указатель на слип-блокировку
  f->mutex = 0;
}
